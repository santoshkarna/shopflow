-- product_id: same database → foreign key. order_id: Ordering context (order_db) → plain id, no foreign key.
CREATE TABLE stock_reservations (
                                    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                    order_id   BIGINT                   NOT NULL,
                                    product_id BIGINT                   NOT NULL,
                                    quantity   INTEGER                  NOT NULL,
                                    status     VARCHAR(20)              NOT NULL,
                                    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                                    CONSTRAINT pk_stock_reservations               PRIMARY KEY (id),
                                    CONSTRAINT uk_stock_reservations_order_product UNIQUE (order_id, product_id),
                                    CONSTRAINT fk_stock_reservations_product       FOREIGN KEY (product_id) REFERENCES products (id),
                                    CONSTRAINT ck_stock_reservations_quantity      CHECK (quantity > 0),
                                    CONSTRAINT ck_stock_reservations_status        CHECK (status IN ('RESERVED', 'CONFIRMED', 'RELEASED', 'EXPIRED'))
);